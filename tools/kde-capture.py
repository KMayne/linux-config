#!/usr/bin/env python3
"""Print this machine's KDE customisations in the format of home/.chezmoidata/plasma.yaml.

Run it on the machine whose setup you want to copy, review the output, and paste the
parts you want to keep into plasma.yaml:

    curl -fsSL https://raw.githubusercontent.com/KMayne/linux-config/main/tools/kde-capture.py | python3 - > kde-capture.yaml

Read-only: it never changes anything. Covers:
  - global shortcuts that differ from their defaults (kglobalshortcutsrc)
  - settings in the main Plasma/KWin/Konsole config files, minus obvious window-state noise
  - custom command shortcuts and Konsole profiles/colour schemes, printed as comments
"""
import json
import os
import re
from pathlib import Path

HOME = Path.home()
CONFIG = Path(os.environ.get("XDG_CONFIG_HOME") or HOME / ".config")
DATA = Path(os.environ.get("XDG_DATA_HOME") or HOME / ".local/share")

SETTINGS_FILES = [
    "kdeglobals", "kwinrc", "kcminputrc", "kxkbrc", "plasmarc", "ksmserverrc",
    "kscreenlockerrc", "powerdevilrc", "krunnerrc", "plasmanotifyrc", "klaunchrc",
    "breezerc", "kwinrulesrc", "dolphinrc", "konsolerc", "spectaclerc",
]
# Machine-specific or UI-state groups/keys that shouldn't be synced
SKIP_GROUP = re.compile(r"^(\$Version|MainWindow|KFileDialog Settings|Colors:|ColorEffects:|WM$|Tiling|"
                        r"Notification Messages|Recent|.*State$|PreviewSettings|General\]\[Recent)", re.I)
SKIP_KEY = re.compile(r"(geometry|^(width|height)\b|^size$|^state$|position|maximized|recent|"
                      r"history|^Id_\d|ScaleFactor|^Scale$|forceFontDPI|^\d+ screens:|ToolBarsMovable|"
                      r"^ConfigVersion$|^Version$|^update_info$|Hash$|Timestamp$)", re.I)
# Shortcuts generated by tools rather than set by hand (ror writes its own from ~/.config/ror)
SKIP_ACTION = re.compile(r"^(_k_|ror-)")


def unescape(s):
    out, i = [], 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s):
            out.append({"t": "\t", "n": "\n", "s": " ", "\\": "\\"}.get(s[i + 1], s[i + 1]))
            i += 2
        else:
            out.append(s[i])
            i += 1
    return "".join(out)


def parse_kconfig(path):
    """{group: {key: value}}; nested groups are joined as 'A][B' like the file itself."""
    groups, group = {}, None
    for line in path.read_text(errors="replace").splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("[") and line.endswith("]"):
            group = line[1:-1]
            groups.setdefault(group, {})
        elif "=" in line and group is not None:
            key, value = line.split("=", 1)
            key = re.sub(r"\[\$[a-z]+\]$", "", key.strip())  # drop [$e]/[$i] flags
            groups[group][key] = unescape(value)
    return groups


def q(s):
    return json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML


def keys_list(spec):
    return [] if spec in ("", "none") else spec.split("\t")


def main():
    print("# KDE customisations captured by tools/kde-capture.py")
    print("# Review, then copy what you want into home/.chezmoidata/plasma.yaml")
    print("plasma:")

    # Shortcuts: each value is "current,default,friendly name"
    print("  shortcuts:")
    services = {}
    path = CONFIG / "kglobalshortcutsrc"
    if path.exists():
        for group, entries in parse_kconfig(path).items():
            if group.startswith("services]["):
                services[group.split("][", 1)[1]] = entries
                continue
            changed = []
            for action, value in entries.items():
                if SKIP_ACTION.search(action):
                    continue
                parts = value.split(",", 2) + ["", ""]
                current, default, name = parts[:3]
                if keys_list(current) != keys_list(default):
                    changed.append((action, keys_list(current), default, name))
            if changed:
                print(f"    {q(group)}:")
                for action, keys, default, name in changed:
                    print(f"      {q(action)}: {json.dumps(keys)}"
                          f"  # default: {default.replace(chr(9), ', ') or 'none'} ({name})")

    # Plain settings
    print("  config:")
    for fname in SETTINGS_FILES:
        path = CONFIG / fname
        if not path.exists():
            continue
        lines = []
        for group, entries in parse_kconfig(path).items():
            if SKIP_GROUP.search(group):
                continue
            if group.startswith("Libinput]["):
                lines.append(f"      # {q(group)} is tied to this machine's device IDs")
            kept = {k: v for k, v in entries.items() if not SKIP_KEY.search(k)}
            if kept:
                lines.append(f"      {q(group)}:")
                lines += [f"        {q(k)}: {q(v)}" for k, v in kept.items()]
        if lines:
            print(f"    {fname}:")
            print("\n".join(lines))

    # Custom command shortcuts (System Settings > Shortcuts > Add New > Command)
    if services:
        print("\n# Custom command shortcuts (not applied automatically yet):")
        for desktop, entries in services.items():
            keys = ", ".join(f"{k}={v}" for k, v in entries.items() if not k.startswith("_k_"))
            exec_line = ""
            for d in (DATA / "applications" / desktop, DATA / "kglobalaccel" / desktop):
                if d.exists():
                    exec_line = next((l for l in d.read_text().splitlines() if l.startswith("Exec=")), "")
                    break
            print(f"#   {desktop}: {keys}  {exec_line}")

    # KWin scripts installed per-user (enabled ones show up as <id>Enabled under kwinrc Plugins)
    scripts = DATA / "kwin" / "scripts"
    if scripts.exists() and any(scripts.iterdir()):
        print("\n# KWin scripts in ~/.local/share/kwin/scripts: " + ", ".join(sorted(d.name for d in scripts.iterdir())))

    # Konsole profiles and colour schemes: whole files, so they can be added to chezmoi as-is
    konsole = DATA / "konsole"
    files = sorted(konsole.glob("*.profile")) + sorted(konsole.glob("*.colorscheme")) if konsole.exists() else []
    for f in files:
        print(f"\n# ==== ~/.local/share/konsole/{f.name} ====")
        for line in f.read_text(errors="replace").splitlines():
            print(f"# {line}")


if __name__ == "__main__":
    main()
